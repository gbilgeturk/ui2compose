from pathlib import Path
import argparse, shutil, random, json
import sys
import yaml
from typing import Optional


SEED = 42
SPLIT = (0.80, 0.10, 0.10)  # train, val, test
IMG_EXTS = (".png", ".jpg", ".jpeg")

def parse_args():
    """Komut satırı argümanlarını tanımlar ve okur.

    Girdi:  yok (değerleri komut satırından alır)
    Çıktı:  args nesnesi — args.labels_root, args.yolo_root gibi ayarlar
    """
    ap = argparse.ArgumentParser()
    ap.add_argument("--labels-root", default="data/interim/labels", type=str,
                    help="parse_redraw çıktıları kökü")
    ap.add_argument("--images-root", default="data/raw", type=str,
                    help="ReDraw görselleri kökü")
    ap.add_argument("--yolo-root", default="data/yolo", type=str,
                    help="YOLO dataset hedefi")
    ap.add_argument("--dataset-yaml", default="configs/dataset.yaml", type=str,
                    help="(ops) mevcut YAML; yoksa yazılabilir")
    ap.add_argument("--write-yaml", action="store_true",
                    help="Var olan YAML'ı yeniden yaz (names için aynı dosyayı okur)")
    ap.add_argument("--clean", action="store_true",
                    help="Önce data/yolo klasörünü temizle")
    ap.add_argument("--symlink", action="store_true",
                    help="Görüntüleri kopyalamak yerine symlink oluştur")
    ap.add_argument("--names-json", default=None, type=str,
                    help="(ops) İstersen sınıf listesini JSON ile ver: \"['Button', ...]\"")
    return ap.parse_args()

# ---------- yardımcılar ----------

def link_or_copy(src: Path, dst: Path, symlink=False):
    """Görüntü dosyasını hedefe symlink olarak bağlar veya kopyalar.

    Girdi:  src — kaynak dosya yolu; dst — hedef dosya yolu;
            symlink — True ise kopya yerine symlink dener
    Çıktı:  yok (dst konumunda dosya/symlink oluşturma yan etkisi;
            symlink başarısız olursa kopyaya düşer)
    """
    dst.parent.mkdir(parents=True, exist_ok=True)
    if symlink:
        try:
            if dst.exists() or dst.is_symlink():
                dst.unlink()
            dst.symlink_to(src)
        except OSError:
            # Bazı dosya sistemlerinde izin yoksa kopyaya düş
            shutil.copy2(src, dst)
    else:
        shutil.copy2(src, dst)

def non_empty_label(path: Path) -> bool:
    """Label dosyasında en az bir geçerli YOLO satırı (5+ alan) olup olmadığını denetler.

    Girdi:  path — kontrol edilecek .txt label dosyasının yolu
    Çıktı:  bool — geçerli satır varsa True, boşsa/okunamıyorsa False
    """
    try:
        for ln in path.read_text(encoding="utf-8").splitlines():
            if len(ln.split()) >= 5:
                return True
    except Exception:
        pass
    return False

def unique_name(app: str, stem: str) -> str:
    """Uygulama adı ile dosya kökünü birleştirip çakışmasız dosya adı üretir.

    Girdi:  app — uygulama klasörünün adı; stem — ekran görüntüsü kökü, örn. "screenshot_1"
    Çıktı:  "app_stem" biçiminde benzersiz ad (uzun ama çakışmasız)
    """
    return f"{app}_{stem}"

def find_image_for(app_dir: Path, stem: str):
    """Verilen köke karşılık gelen görüntü dosyasını uzantıları deneyerek arar.

    Girdi:  app_dir — uygulamanın ham görsel klasörü; stem — dosya kökü, örn. "screenshot_1"
    Çıktı:  bulunan görüntünün Path'i (.png/.jpg/.jpeg); yoksa None
    """
    for ext in IMG_EXTS:
        p = app_dir / f"{stem}{ext}"
        if p.exists():
            return p
    return None

def load_names(yaml_path: Path, override_json: Optional[str]):
    """Sınıf isim listesini önce JSON override'dan, yoksa dataset.yaml'dan okur.

    Girdi:  yaml_path — 'names' listesini içeren YAML dosyasının yolu;
            override_json — (ops) JSON metni veya JSON dosya yolu
    Çıktı:  names — sıralı sınıf isimleri listesi; hiçbir kaynak yoksa boş liste
    """
    # 1) JSON ile override
    if override_json:
        try:
            if Path(override_json).exists():
                return json.loads(Path(override_json).read_text(encoding="utf-8"))
            return json.loads(override_json)
        except Exception:
            print("[WARN] names-json parse edilemedi; dataset.yaml kullanılacak.")
    # 2) dataset.yaml'dan oku
    if yaml_path.exists():
        data = yaml.safe_load(open(yaml_path, "r", encoding="utf-8"))
        names = data.get("names", [])
        if names:
            return names
    return []

def write_dataset_yaml(out_yaml: Path, yolo_root: Path, names: list[str]):
    """YOLO eğitimi için path/train/val/test/nc/names alanlı dataset.yaml dosyasını üretir.

    Girdi:  out_yaml — yazılacak YAML dosyasının yolu; yolo_root — dataset kök dizini;
            names — sınıf isimleri listesi (boşsa nc=0 yazılır)
    Çıktı:  yok (out_yaml dosyasını oluşturma/üzerine yazma yan etkisi)
    """
    out_yaml.parent.mkdir(parents=True, exist_ok=True)
    nc = len(names) if names else 0
    text = (
        f"# autogenerated\n"
        f"path: {yolo_root.resolve()}\n"
        f"train: images/train\n"
        f"val: images/val\n"
        f"test: images/test\n"
        f"nc: {nc}\n"
        f"names:\n"
    )
    for n in names:
        text += f"  - {n}\n"
    out_yaml.write_text(text, encoding="utf-8")

# ---------- ana akış ----------

def main():
    """Label-görsel çiftlerini eşleştirip 80/10/10 oranında YOLO dataset'ini kurar.

    Girdi:  yok (ayarları parse_args üzerinden komut satırından alır)
    Çıktı:  yok (data/yolo altına images/labels kopyalama, istenirse
            dataset.yaml yazma ve özet çıktısı basma yan etkisi)
    """
    args = parse_args()
    labels_root = Path(args.labels_root)
    images_root = Path(args.images_root)
    yolo_root   = Path(args.yolo_root)
    yaml_path   = Path(args.dataset_yaml)

    if not labels_root.exists():
        print(f"[ERR] labels-root yok: {labels_root}"); sys.exit(1)
    if not images_root.exists():
        print(f"[ERR] images-root yok: {images_root}"); sys.exit(1)

    # Temiz başlat
    if args.clean and yolo_root.exists():
        shutil.rmtree(yolo_root)

    # Hedef dizinleri hazırla
    for sub in ["images/train", "images/val", "images/test",
                "labels/train", "labels/val", "labels/test"]:
        (yolo_root / sub).mkdir(parents=True, exist_ok=True)

    # Sınıf isimlerini al (yaml’dan veya json’dan)
    names = load_names(yaml_path, args.names_json)

    # Label klasörlerini gez: data/interim/labels/<app>/*.txt
    pairs = []
    missing_images = []

    for app_dir in sorted(labels_root.iterdir()):
        if not app_dir.is_dir():
            continue
        app = app_dir.name

        # Boş klasörleri atla
        label_files = sorted([p for p in app_dir.glob("*.txt") if non_empty_label(p)])
        if not label_files:
            continue

        # Eşleştir
        raw_app_dir = images_root / app
        for lf in label_files:
            stem = lf.stem  # "screenshot_i"
            img = find_image_for(raw_app_dir, stem)
            if img is None:
                missing_images.append(str(lf))
                continue
            pairs.append((lf, img, app, stem))

    n = len(pairs)
    if n == 0:
        print("✅ YOLO dataset hazırlandı.")
        print("Toplam pair: 0  | train:0 val:0 test:0")
        print(f"Eşleşmeyen görsel sayısı (label var ama image yok): {len(missing_images)}")
        print(f"YAML: {yaml_path.resolve()}")
        print(f"Klasör: {yolo_root.resolve()}")
        return

    # Deterministik split
    random.seed(SEED)
    random.shuffle(pairs)
    t = int(n * SPLIT[0]); v = int(n * SPLIT[1])
    train, val, test = pairs[:t], pairs[t:t+v], pairs[t+v:]

    # Kopyala/bağla
    for subset, items in (("train", train), ("val", val), ("test", test)):
        for lf, img, app, stem in items:
            base = unique_name(app, stem)
            out_img = yolo_root / "images" / subset / (base + img.suffix.lower())
            out_lab = yolo_root / "labels" / subset / (base + ".txt")
            link_or_copy(img, out_img, symlink=args.symlink)
            shutil.copy2(lf, out_lab)

    # YAML yaz (istenirse)
    if args.write-yaml if False else False:
        pass  # (guard for IDE syntax highlighters)

    if args.write_yaml:
        # isim listesi bulunamadıysa bile dosyayı üret (nc=0)
        write_dataset_yaml(yaml_path, yolo_root, names)

    # Özet
    print("✅ YOLO dataset hazırlandı.")
    print(f"Toplam pair: {n}  | train:{len(train)} val:{len(val)} test:{len(test)}")
    print(f"Eşleşmeyen görsel sayısı (label var ama image yok): {len(missing_images)}")
    print(f"YAML: {yaml_path.resolve()}")
    print(f"Klasör: {yolo_root.resolve()}")

if __name__ == "__main__":
    main()