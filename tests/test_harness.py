def test_report_is_current_and_everything_compiled_and_rendered():
    """Every listed file still has the reported SHA-256, compiled and rendered, and its render exists."""
    report = load_report()
    for f in report['files']:
        src = REPO / f['source']
        assert hashlib.sha256(src.read_bytes()).hexdigest() == f['sha256'], f"{f['source']} changed; {RERUN_HINT}"
        assert f['compiled'] and not f['compile_errors'], f
        assert f['rendered'] and f['render_error'] is None, f
        render = REPO / f['render']
        assert render.is_file(), f"{f['render']} missing; {RERUN_HINT}"
        assert H.png_size(render) == f['render_size_px']
    s = report['summary']
    assert s['files'] == s['compiled'] == s['with_screen_function'] == s['rendered'] == len(report['files'])
    assert len({f['package'] for f in report['files']}) == len(report['files'])


