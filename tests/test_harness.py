def test_with_package_inserts_a_directive_before_the_code():
    """A file without a package gets one as its first line; the rest is unchanged."""
    code = "// Generated by ui2compose\n\nimport a.B\n\n@Composable\nfun GeneratedScreen() {}\n"
    out = H.with_package(code, 'generated.s07')
    assert out.split('\n')[0] == 'package generated.s07'
    assert out.endswith(code)
    assert len(re.findall(r'(?m)^package ', out)) == 1


def test_with_package_replaces_an_existing_directive():
    """An existing package directive is replaced, not duplicated."""
    code = "// header\npackage com.example.screens\n\nimport a.B\n"
    out = H.with_package(code, 'generated.s02')
    assert out == "// header\npackage generated.s02\n\nimport a.B\n"


def test_with_package_goes_after_file_annotations():
    """@file: annotations must precede the package directive."""
    code = '@file:Suppress("unused")\n\nimport a.B\n'
    lines = H.with_package(code, 'generated.s01').split('\n')
    assert lines[0].startswith('@file:')
    assert lines[1] == 'package generated.s01'


