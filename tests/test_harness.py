def test_all_templates_fixture_exercises_every_template():
    """Every class template, both progress shapes, Row weights, lists with and without items and containment occur."""
    sized = (FIXTURES / 'all_templates_sized.kt').read_text(encoding='utf-8')
    leaf_classes = set(re.findall(r'// leaf (\w+)#', sized))
    assert leaf_classes == set(DATASET_CLASSES) - {'RecyclerView'} | {'FancyWidget'}
    assert '// LazyColumn (rule=list, list container RecyclerView#17' in sized
    fixed = (FIXTURES / 'all_templates_xycut.kt').read_text(encoding='utf-8')
    for call in ('Button(', 'Text(', 'TextField(', 'Image(', 'Checkbox(', 'Switch(', 'RadioButton(',
                 'Slider(', 'CircularProgressIndicator(', 'LinearProgressIndicator(', 'OutlinedButton(',
                 'DropdownMenu(', 'DropdownMenuItem(', 'AndroidView(', 'LazyColumn(', 'Box(', 'Row(', 'Column('):
        assert call in fixed, call
    assert fixed.count('LazyColumn(') == 2
    assert 'Text("ListView: no items detected")' in fixed
    assert 'Text("Unknown: FancyWidget")' in fixed
    # Full-width templates and the list inside a Row use weight(1f).
    assert len(re.findall(r'Modifier\.weight\(1f\)', fixed)) >= 4
    gen = ComposeCodeGenerator()
    gen.generate(all_templates_graph())
    tree = gen.last_layout_tree
    lazy = [c for c in tree['children'] if c['type'] == 'LazyColumn']
    assert len(lazy) == 1 and [c['type'] for c in lazy[0]['children']] == ['Row', 'Box']
    flat = (FIXTURES / 'all_templates_flat.kt').read_text(encoding='utf-8')
    assert 'RecyclerView: 3 child detection(s) emitted separately (flat layout)' in flat


