def test_parse_kotlin_diagnostics_decodes_file_uris():
    """e:/w: lines are grouped per file; percent-encoded file URIs (spaces) are decoded."""
    log = "\n".join([
        "> Task :screens:compileDebugKotlin FAILED",
        "e: file:///Users/a/Application%20Support/s02/GeneratedScreen.kt:8:5 Unresolved reference 'Foo'.",
        "w: file:///Users/a/Application%20Support/s02/GeneratedScreen.kt:3:1 Something is deprecated.",
        "e: /plain/path/s03/GeneratedScreen.kt:1:1 Syntax error.",
        "e: Compilation error. See log for more details",
    ])
    d = H.parse_kotlin_diagnostics(log)
    assert d['/Users/a/Application Support/s02/GeneratedScreen.kt'] == {
        'errors': ["8:5 Unresolved reference 'Foo'."], 'warnings': ['3:1 Something is deprecated.']}
    assert d['/plain/path/s03/GeneratedScreen.kt']['errors'] == ['1:1 Syntax error.']
    assert len(d) == 2


