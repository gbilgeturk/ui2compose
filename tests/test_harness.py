def _load_harness():
    """Imports harness/compile_and_render.py as a module (harness/ is not a package).

    Input:  none
    Output: module object
    """
    spec = importlib.util.spec_from_file_location('ui2compose_harness', HARNESS / 'compile_and_render.py')
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


H = _load_harness()


def fake_png(width: int, height: int) -> bytes:
    """Returns the first bytes of a PNG file (signature and IHDR) of the given size.

    Input:  width, height — pixel size
    Output: bytes (enough for png_size)
    """
    return (b'\x89PNG\r\n\x1a\n' + struct.pack('>I', 13) + b'IHDR'
            + struct.pack('>IIBBBBB', width, height, 8, 6, 0, 0, 0) + b'\0\0\0\0')


def write_kt(path: Path, body: str = "fun GeneratedScreen() {\n}\n") -> Path:
    """Writes a small Kotlin file.

    Input:  path — target file; body — Kotlin source
    Output: path
    """
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(body, encoding='utf-8')
    return path


