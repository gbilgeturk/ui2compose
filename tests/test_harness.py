def fake_setup(tmp_path: Path, monkeypatch) -> Tuple[Path, List[str]]:
    """Points the harness at a temporary Gradle project, JDK and SDK (no real tools are run).

    Input:  tmp_path — base directory; monkeypatch — pytest fixture
    Output: (temporary android dir, common command-line options)
    """
    android = tmp_path / 'android'
    for rel in ('gradle/libs.versions.toml', 'gradle/wrapper/gradle-wrapper.properties',
                'screens/build.gradle.kts'):
        dst = android / rel
        dst.parent.mkdir(parents=True, exist_ok=True)
        dst.write_text((HARNESS / 'android' / rel).read_text(encoding='utf-8'), encoding='utf-8')
    jdk, sdk = tmp_path / 'jdk', tmp_path / 'sdk'
    (jdk / 'bin').mkdir(parents=True)
    (jdk / 'bin' / 'java').write_text('')
    (sdk / 'platforms' / 'android-34').mkdir(parents=True)
    monkeypatch.setattr(H, 'ANDROID_DIR', android)
    monkeypatch.setattr(H, 'java_version', lambda java_home: '17.0.0')
    return android, ['--java-home', str(jdk), '--sdk-dir', str(sdk)]


def test_main_compile_only_writes_report_and_local_properties(tmp_path, monkeypatch):
    """--compile-only: exit 0 when all compile; nothing is rendered; the SDK path goes to local.properties."""
    android, opts = fake_setup(tmp_path, monkeypatch)
    src = write_kt(tmp_path / 'in' / 'a' / '4_GeneratedScreen.kt')
    old_render = src.parent / 'render.png'
    old_render.write_bytes(fake_png(1, 1))
    tasks_seen: List[List[str]] = []

    def fake_gradle(tasks, android_dir, env, log_path, offline=False):
        """Accepts every compile; records the tasks."""
        tasks_seen.append(list(tasks))
        assert env['JAVA_HOME'] == opts[1]
        return 0, ''

    monkeypatch.setattr(H, 'run_gradle', fake_gradle)
    report_file = tmp_path / 'report.json'
    assert H.main([str(tmp_path / 'in'), '--compile-only', '--report', str(report_file)] + opts) == 0
    assert all(':screens:recordPaparazziDebug' not in t for t in tasks_seen)
    assert (android / 'local.properties').read_text() == f"sdk.dir={opts[3]}\n"
    report = json.loads(report_file.read_text(encoding='utf-8'))
    entry, = report['files']
    assert entry['compiled'] and not entry['rendered']
    assert entry['render_error'] == 'rendering skipped (--compile-only)'
    assert report['toolchain']['jdk'] == '17.0.0' and report['toolchain']['kotlin'] == '2.0.21'
    assert old_render.exists()


