def test_render_places_pngs_and_removes_stale_renders(tmp_path, monkeypatch):
    """A passing snapshot is copied next to its source; a failing one leaves no render behind."""
    android = tmp_path / 'android'
    screens = make_screens(tmp_path, 3)
    screens[0].compiled = screens[1].compiled = True
    screens[2].compiled = False
    stale = screens[1].source.parent / 'render.png'
    stale.write_bytes(fake_png(1, 1))
    stale_uncompiled = screens[2].source.parent / 'render.png'
    stale_uncompiled.write_bytes(fake_png(1, 1))

    def fake_gradle(tasks, android_dir, env, log_path, offline=False):
        """Writes a snapshot for s01 (passing) and a failing result for s02."""
        assert tasks == [':screens:recordPaparazziDebug']
        assert screens[0].test_path(android_dir).is_file() and screens[1].test_path(android_dir).is_file()
        assert not screens[2].copy_path(android_dir).exists()
        images = android_dir / H._SNAPSHOT_IMAGES
        images.mkdir(parents=True)
        (images / 'generated.s01_GeneratedScreenSnapshotTest_render.png').write_bytes(fake_png(625, 1000))
        results = android_dir / H._TEST_RESULTS
        write_junit(results, 'generated.s01.GeneratedScreenSnapshotTest')
        write_junit(results, 'generated.s02.GeneratedScreenSnapshotTest', failure='layout crash')
        return 1, "BUILD FAILED"

    monkeypatch.setattr(H, 'run_gradle', fake_gradle)
    H.render_screens(screens, android, {}, tmp_path / 'logs', False, tmp_path / 'renders', True)
    assert screens[0].rendered and screens[0].render == screens[0].source.parent / 'render.png'
    assert screens[0].render_size == [625, 1000]
    assert not screens[1].rendered and screens[1].render_error == 'failure: layout crash'
    assert screens[2].render_error == 'not compiled'
    assert not stale.exists() and not stale_uncompiled.exists()
    report = H.build_report(screens, {'kotlin': 'x'}, tmp_path / 'renders')
    assert report['summary'] == {'files': 3, 'compiled': 2, 'with_screen_function': 3, 'rendered': 1}


