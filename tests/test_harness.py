# ── compile and render rounds (Gradle replaced by fakes) ──

def make_screens(tmp_path: Path, n: int) -> List:
    """Creates n source files in their own directories and their Screen objects.

    Input:  tmp_path — base directory; n — number of screens
    Output: list of harness Screen objects
    """
    sources = [write_kt(tmp_path / 'src' / f'screen{i}' / '4_GeneratedScreen.kt') for i in range(n)]
    return [H.Screen(s, p) for s, p in zip(sources, H.package_names(n))]


def uri(path: Path) -> str:
    """Returns the percent-encoded file URI the Kotlin compiler prints for a path.

    Input:  path — absolute path
    Output: 'file://...' string
    """
    return path.resolve().as_uri()


def test_compile_drops_failing_files_and_recompiles_the_rest(tmp_path, monkeypatch):
    """A file with errors is marked as not compiled; the others are compiled in the next round."""
    android = tmp_path / 'android'
    screens = make_screens(tmp_path, 3)
    calls: List[Tuple[Sequence[str], List[str]]] = []

    def fake_gradle(tasks, android_dir, env, log_path, offline=False):
        """Round 1 fails with an error in s02 (and warns in s03); round 2 succeeds with a warning in s01."""
        present = sorted(p.name for p in (android_dir / H._MAIN_SRC).iterdir())
        calls.append((list(tasks), present))
        s1, s2, s3 = (s.copy_path(android_dir) for s in screens)
        if len(calls) == 1:
            return 1, (f"RESOLVED androidx.compose.material3:material3=1.2.1\n"
                       f"e: {uri(s2)}:2:1 Bad thing.\nw: {uri(s3)}:1:1 Old warning.\n")
        return 0, f"w: {uri(s1)}:1:1 Deprecated thing.\n"

    monkeypatch.setattr(H, 'run_gradle', fake_gradle)
    resolved = H.compile_screens(screens, android, {}, tmp_path / 'logs', offline=False)
    assert resolved == {'androidx.compose.material3:material3': '1.2.1'}
    assert [c[1] for c in calls] == [['s01', 's02', 's03'], ['s01', 's03']]
    assert calls[0][0][0] == ':screens:printResolvedVersions' and '--rerun' in calls[1][0]
    assert [s.compiled for s in screens] == [True, False, True]
    assert screens[1].errors == ['2:1 Bad thing.']
    assert screens[0].warnings == ['1:1 Deprecated thing.']
    assert screens[2].errors == [] and screens[2].warnings == []   # diagnostics of the last round only
    copy = screens[0].copy_path(android).read_text(encoding='utf-8')
    assert copy.startswith('package generated.s01\n')


