def write_junit(results_dir: Path, classname: str, failure: str = None):
    """Writes a JUnit XML result file with one test case.

    Input:  results_dir — target directory; classname — test class; failure —
            failure message or None for a passing test
    Output: none (side effect of writing TEST-<classname>.xml)
    """
    results_dir.mkdir(parents=True, exist_ok=True)
    inner = f'<failure message="{failure}" type="java.lang.IllegalStateException">trace</failure>' if failure else ''
    (results_dir / f'TEST-{classname}.xml').write_text(
        f'<?xml version="1.0" encoding="UTF-8"?>\n<testsuite name="{classname}" tests="1">'
        f'<testcase name="render" classname="{classname}" time="0.1">{inner}</testcase></testsuite>\n',
        encoding='utf-8')


def test_parse_junit_results(tmp_path):
    """Passing and failing test classes are read from the JUnit XML files."""
    write_junit(tmp_path, 'generated.s01.GeneratedScreenSnapshotTest')
